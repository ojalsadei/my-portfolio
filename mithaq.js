function renderStep(
  shouldScroll =
    true
) {

  showingResult =
    false;


  const steps =
    getActiveSteps();


  if (
    currentStep >=
    steps.length
  ) {

    currentStep =
      Math.max(
        0,
        steps.length - 1
      );

  }


  const step =
    steps[currentStep];


  if (
    !step
  ) {

    renderResult(
      shouldScroll
    );

    return;

  }


  stepTitle.textContent =
    step.title;


  stepCurrent.textContent =
    String(
      currentStep + 1
    );


  stepTotal.textContent =
    String(
      steps.length + 1
    );


  progressBar.style.width =
    `${
      (
        (
          currentStep + 1
        ) /
        (
          steps.length + 1
        )
      ) * 100
    }%`;


  backButton.disabled =
    false;


  stepContent.innerHTML = `
    <div class="options-grid">

      ${step.options
        .map(
          (
            [
              value,
              title,
              description
            ]
          ) =>
            createOption(
              value,
              title,
              description
            )
        )
        .join("")}

    </div>
  `;


  document
    .querySelectorAll(
      "[data-value]"
    )
    .forEach(
      button => {

        button.addEventListener(
          "click",
          () => {

            answers[
              step.key
            ] =
              button.dataset.value;


            const updatedSteps =
              getActiveSteps();


            if (
              currentStep <
              updatedSteps.length - 1
            ) {

              currentStep +=
                1;


              renderStep(
                true
              );

            } else {

              renderResult(
                true
              );

            }

          }
        );

      }
    );


  if (
    shouldScroll
  ) {

    scrollToQuestion();

  }

}



