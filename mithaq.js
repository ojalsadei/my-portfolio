document
  .querySelectorAll(
    ".horizontal-rail"
  )
  .forEach(
    rail => {

      let dragging =
        false;


      let startX =
        0;


      let startScroll =
        0;


      rail.addEventListener(
        "pointerdown",
        event => {

          if (
            event.target.closest(
              "a, button"
            )
          ) {
            return;
          }


          dragging =
            true;


          startX =
            event.clientX;


          startScroll =
            rail.scrollLeft;


          rail.classList.add(
            "is-dragging"
          );


          rail.setPointerCapture(
            event.pointerId
          );

        }
      );


      rail.addEventListener(
        "pointermove",
        event => {

          if (
            !dragging
          ) {
            return;
          }


          const distance =
            event.clientX -
            startX;


          rail.scrollLeft =
            startScroll -
            distance;

        }
      );


      const stopDragging =
        event => {

          if (
            !dragging
          ) {
            return;
          }


          dragging =
            false;


          rail.classList.remove(
            "is-dragging"
          );


          if (
            event.pointerId !==
            undefined
          ) {

            try {

              rail.releasePointerCapture(
                event.pointerId
              );

            } catch {
            }

          }

        };


      rail.addEventListener(
        "pointerup",
        stopDragging
      );


      rail.addEventListener(
        "pointercancel",
        stopDragging
      );

    }
  );



