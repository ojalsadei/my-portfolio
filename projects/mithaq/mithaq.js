function moveRail(
  railId,
  direction
) {

  const rail =
    document.getElementById(
      railId
    );


  if (
    !rail
  ) {
    return;
  }


  const amount =
    Math.min(
      rail.clientWidth * 0.78,
      520
    );


  rail.scrollBy({
    left:
      direction * amount,

    behavior:
      reducedMotion
        ? "auto"
        : "smooth"
  });

}



