function scrollToQuestion() {

  requestAnimationFrame(
    () => {

      const rect =
        navigator.getBoundingClientRect();


      const targetTop =
        120;


      const difference =
        rect.top -
        targetTop;


      if (
        Math.abs(
          difference
        ) > 55
      ) {

        window.scrollTo({
          top:
            window.scrollY +
            difference,

          behavior:
            reducedMotion
              ? "auto"
              : "smooth"
        });

      }

    }
  );

}



